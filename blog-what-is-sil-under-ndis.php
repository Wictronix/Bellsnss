                                    <ul class="compassion-list" style="list-style: none; padding-left: 0;">
                                        <li><strong>Q: Can I choose who I live with in a SIL arrangement?</strong><br>A:
                                            Participants can express preferences about housemates and living
                                            arrangements. While the NDIA cannot guarantee specific housemates, providers
                                            and support coordinators work hard to facilitate compatible household
                                            matches.</li>
                                        <li><strong>Q: Does SIL funding include rent or mortgage
                                                payments?</strong><br>A: No. SIL funding covers the cost of support
                                            workers only. Rent or housing costs are paid separately , either through
                                            standard accommodation (rent, Centrelink Rent Assistance) or SDA funding if
                                            eligible.</li>
                                        <li><strong>Q: Can I have SIL funding if I live with family?</strong><br>A:
                                            Generally, SIL is not funded for participants living with family in the
                                            family home. It applies to living arrangements where support workers are
                                            required to be present. In some circumstances, exceptional SIL funding for
                                            family homes April be considered.</li>
