                                <p class="lead">Supported Independent Living , better known as SIL , is one of the most
                                    significant and life-changing supports available under the NDIS. For Melbourne
                                    participants who want to live more independently but require around-the-clock or
                                    high-frequency support, SIL funding can make that a reality. This guide explains
                                    what SIL is, who qualifies, how the funding works, and how to begin the process of
                                    accessing it.</p>

                                <h3>What Is Supported Independent Living (SIL)?</h3>
                                <p>SIL is an NDIS support that funds assistance with daily tasks in a shared or
                                    individual living arrangement, enabling participants who cannot live independently
                                    without significant support to do so in a home setting rather than a clinical
                                    facility. SIL funding pays for the support workers who assist participants with
                                    their daily routines , things like personal care, meal preparation, medication
                                    management, and overnight supervision , rather than the physical accommodation
                                    itself. It can be provided in a shared house with other NDIS participants, in an
                                    individual home, or within a Specialist Disability Accommodation (SDA) property.</p>

                                <h3>Who Is SIL For?</h3>
                                <p>SIL is designed for participants who:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li>Require daily or overnight support that cannot be provided by informal carers
                                    </li>
                                    <li>Want to live independently but need high levels of active support</li>
                                    <li>Are transitioning out of a hospital, group home, or family home</li>
                                    <li>Have complex support needs requiring consistent, structured care</li>
                                </ul>
                                <p>The NDIA assesses each participant's SIL needs through a SIL assessment process,
                                    which typically involves an occupational therapist report, a SIL Roster of Care, and
                                    supporting documentation from your care team. Because SIL involves significant
                                    ongoing funding, the assessment is thorough.</p>

                                <h3>How Does SIL Funding Work?</h3>
                                <p>SIL is funded under Core Supports , Assistance with Daily Life (Category 01) in your
                                    NDIS plan. Unlike most NDIS supports which have a set hourly rate, SIL funding is
                                    calculated as a Roster of Care , a detailed breakdown of the specific support hours
                                    and staffing ratios required each day of the week. For example, a participant April
                                    need one-to-one active support during waking hours and overnight supervision, which
                                    translates to a specific weekly funding amount. The NDIA reviews the Roster of Care
                                    and approves a total SIL amount that reflects the actual staffing cost of the
                                    support model.</p>
                                <p>The 2025-26 NDIS Price Guide rates for SIL supports vary based on the ratio of
                                    support (1:1, 1:2, 1:3) and the time of day, with overnight monitoring rates
                                    differing from active overnight support rates.</p>

                                <h3>SIL vs SDA , What Is the Difference?</h3>
                                <p>This is one of the most commonly confused distinctions in the NDIS. SIL is the
                                    support funding , it pays for the workers. SDA (Specialist Disability Accommodation)
                                    is the housing funding , it pays for the physical property. Not all SIL participants
                                    live in SDA. Many live in standard rental properties or shared houses, with the SIL
                                    provider funding the support staffing. SDA is a separate, additional funding stream
                                    for participants who require purpose-built, accessible housing.</p>

                                <h3>What Does Daily Life Look Like With SIL?</h3>
                                <p>In a SIL arrangement, you typically live in a shared house with two to four other
                                    NDIS participants, with a support team rostered across the week. Your day might
                                    include:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li>Assistance with morning personal care and preparing for the day</li>
                                    <li>Support to attend community activities, appointments, and social events</li>
                                    <li>Meal preparation and shared household tasks</li>
                                    <li>Evening support with medication, hygiene, and settling in for the night</li>
                                    <li>Overnight supervision or active overnight support as required</li>
                                </ul>
                                <p>At Bell's NSS, SIL support is tailored to each participant's goals , not a
                                    one-size-fits-all roster. We work with participants, families, and support
                                    coordinators to design a living arrangement and support model that genuinely
                                    reflects the participant's preferences and aspirations.</p>

                                <h3>How to Apply for SIL in Melbourne</h3>
                                <p>1. Speak with your support coordinator , they coordinate the SIL assessment and NDIA
                                    submission process.<br>
                                    2. Commission an occupational therapist assessment documenting your functional
                                    capacity and support needs.<br>
                                    3. Develop a Roster of Care with a SIL provider, detailing proposed support hours
                                    and staffing.<br>
                                    4. Submit to the NDIA for consideration at your next plan review or via a formal
                                    plan change request.</p>

