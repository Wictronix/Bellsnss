                                <p class="lead">When you receive your first NDIS plan , or review your current one , one
                                    of the most important decisions you will make is how your funding is managed. The
                                    three options are NDIA-managed, plan-managed, and self-managed, and each comes with
                                    different levels of flexibility, administrative responsibility, and provider choice.
                                    This guide breaks them down in plain English so you can make the right decision for
                                    your situation.</p>

                                <h3>Option 1: NDIA-Managed (Agency-Managed)</h3>
                                <p>If your plan is NDIA-managed, the National Disability Insurance Agency manages your
                                    funding directly. Providers claim payments through the NDIS online portal after
                                    delivering each service. You do not handle any invoicing or payment yourself.
                                    <br><br><strong>Who it suits:</strong> Participants who want a simple, hands-off
                                    approach with strong financial safeguards , particularly those new to the NDIS or
                                    managing complex support arrangements.
                                    <br><strong>Limitation:</strong> You can only use registered NDIS providers. This
                                    restricts your choices to providers who have passed the NDIS quality audits and are
                                    listed on the NDIS Provider Register.
                                </p>

                                <h3>Option 2: Plan-Managed</h3>
                                <p>With a plan-managed plan, a registered plan manager , a financial intermediary funded
                                    separately by your NDIS plan , handles all invoicing, payments, and financial
                                    record-keeping on your behalf.
                                    <br><br><strong>Who it suits:</strong> Participants who want the flexibility to use
                                    both registered and unregistered providers without taking on the administrative
                                    burden themselves. This is the most popular option in Australia, used by over 65% of
                                    NDIS participants nationally.
                                    <br><strong>Key benefit:</strong> Your plan manager pays all provider invoices
                                    directly and provides you with regular spending statements so you can track your
                                    budget without managing paperwork yourself.
                                </p>

                                <h3>Option 3: Self-Managed</h3>
                                <p>Self-management gives you the most flexibility and control over your NDIS funding.
                                    You manage your own budget, pay providers and support workers directly, and claim
                                    reimbursements through the NDIS portal , or use a nominee to do this on your behalf.
                                    <br><br><strong>Who it suits:</strong> Participants who are confident managing
                                    budgets, want to hire private support workers, or have very specific support
                                    arrangements not easily met through registered providers.
                                    <br><strong>Consideration:</strong> Self-management requires time, organisation, and
                                    financial literacy. You are responsible for keeping records, ensuring workers are
                                    paid correctly, and managing NDIS budget categories accurately.
                                </p>

                                <h3>Comparing the Three Options</h3>
                                <p>Here is a straightforward comparison to help you decide:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li><strong>Flexibility in provider choice:</strong> NDIA-managed = registered only
                                        | Plan-managed = registered + unregistered | Self-managed = full flexibility
                                    </li>
                                    <li><strong>Administrative work:</strong> NDIA-managed = none | Plan-managed =
                                        minimal | Self-managed = significant</li>
                                    <li><strong>Financial oversight:</strong> NDIA-managed = full NDIA oversight |
                                        Plan-managed = plan manager oversight | Self-managed = self-directed</li>
                                    <li><strong>Additional funding for management:</strong> NDIA-managed = none |
                                        Plan-managed = yes, funded separately | Self-managed = none</li>
                                    <li><strong>Best for:</strong> NDIA-managed = simplicity | Plan-managed =
                                        flexibility + support | Self-managed = maximum control</li>
                                </ul>

                                <h3>Can You Change Your Plan Management Type?</h3>
                                <p>Yes. You can request a change to your plan management type at your next scheduled
                                    plan review or by requesting an unscheduled plan review if your circumstances have
                                    changed significantly. In practice, switching from NDIA-managed to plan-managed is
                                    relatively straightforward and can give you access to a much wider range of
                                    providers , including Bell's NSS , without taking on administrative work.</p>

                                <h3>How Bell's NSS Works With All Plan Types</h3>
                                <p>Bell's NSS works with NDIA-managed, plan-managed, and self-managed participants
                                    across Melbourne. For NDIA-managed participants, we claim directly through the NDIS
                                    portal after each service. For plan-managed participants, we invoice your plan
                                    manager directly. For self-managed participants, we provide clear, detailed invoices
                                    for you to process. Our intake team can walk you through your plan details and
                                    confirm exactly how billing will work before your first service begins , so there
                                    are never any surprises.</p>

