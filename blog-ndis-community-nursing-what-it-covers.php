                                <p class="lead">If you or a family member has complex medical needs and you want to stay
                                    at home rather than in a hospital or care facility, NDIS community nursing could be
                                    exactly the support you need. As a registered NDIS provider in Melbourne, Bell's NSS
                                    provides clinical nursing care directly in participants' homes , delivered by
                                    qualified, AHPRA-registered nurses who understand both the medical and personal
                                    dimensions of disability support.</p>

                                <h3>What Is NDIS Community Nursing?</h3>
                                <p>NDIS community nursing refers to clinical nursing care provided in a participant's
                                    home by a qualified Registered Nurse (RN) or Enrolled Nurse (EN). It is distinct
                                    from standard personal care , which focuses on daily living tasks like showering and
                                    dressing , because it involves medical-grade clinical intervention. Community
                                    nursing under the NDIS is funded primarily under two budget categories: Capacity
                                    Building , Improved Daily Living, and Core Supports , Disability Related Health
                                    Support, depending on the clinical purpose of the support.</p>

                                <h3>What Does NDIS Community Nursing Cover?</h3>
                                <p>Under your NDIS plan, community nursing in Melbourne can fund a wide range of
                                    clinical services, including:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li>Wound care and complex dressing changes</li>
                                    <li>Medication administration and management, including injections and infusions
                                    </li>
                                    <li>Catheter care and continence management</li>
                                    <li>Enteral (tube) feeding and PEG management</li>
                                    <li>Tracheostomy and ventilator support</li>
                                    <li>Chronic disease management , diabetes, cardiac, and respiratory conditions</li>
                                    <li>Pressure injury prevention and care</li>
                                    <li>Palliative and end-of-life comfort care at home</li>
                                    <li>Post-surgical recovery support</li>
                                </ul>
                                <p>Every clinical support is delivered by nurses with verified AHPRA registration,
                                    appropriate clinical training, and , at Bell's NSS , experience specifically in the
                                    disability sector.</p>

                                <h3>Who Can Access NDIS Community Nursing?</h3>
                                <p>To access community nursing through the NDIS, the support must be considered
                                    'reasonable and necessary' and linked to a participant's disability-related health
                                    needs. Eligibility is typically established when:
                                    <br>, The participant has a diagnosed disability with ongoing complex medical needs
                                    <br>, The clinical care cannot reasonably be provided by family carers alone
                                    <br>, The support is directly related to the functional impact of the participant's
                                    disability
                                </p>
                                <p>If nursing is not currently in your plan, a plan review with the NDIA , supported by
                                    medical documentation from your GP or specialist , can be requested to add it.</p>

                                <h3>How Is Community Nursing Different From Personal Care?</h3>
                                <p>This is one of the most common questions participants ask. Personal care is provided
                                    by trained support workers and covers daily tasks like showering, grooming, and
                                    mobility transfers. Community nursing involves clinical medical procedures that must
                                    be performed by a licensed nurse. Some participants require both , for example, a
                                    support worker April assist with showering in the morning while a nurse visits twice
                                    weekly for wound management and medication review. Bell's NSS can coordinate both
                                    within a single care plan.</p>

                                <h3>How Bell's NSS Delivers Community Nursing in Melbourne</h3>
                                <p>At Bell's NSS, our nursing team is not only clinically qualified , many of our nurses
                                    are multilingual, with backgrounds across South Asian, East African, and Southeast
                                    Asian communities. This means your clinical care is delivered by someone who
                                    understands your language, culture, and values. We work with NDIA-managed,
                                    plan-managed, and self-managed participants. Our process is straightforward: contact
                                    us, share your NDIS plan details, and we will arrange an initial nursing assessment
                                    to confirm the scope of care required. There are no out-of-pocket costs for services
                                    covered under your approved plan.</p>

                                <h3>How to Add Community Nursing to Your NDIS Plan</h3>
                                <p>If nursing is not currently funded in your plan, you can:
                                    <br>1. Request a plan review with the NDIA and provide supporting evidence from your
                                    treating clinician
                                    <br>2. Ask your support coordinator to facilitate a formal request for nursing
                                    supports
                                    <br>3. Contact Bell's NSS , we can assist with documenting your nursing needs for
                                    the review process
                                </p>

