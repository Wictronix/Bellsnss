                                <p class="lead">The NDIS can fund community nursing, but figuring out exactly what does NDIS community nursing cover feels like solving a puzzle. One person gets funding for wound care, another gets denied for what seems like the same thing. Let's cut through the confusion.</p>
                                <p>The key word is "disability-related." Not every nursing need qualifies for NDIS funding. Here's what is and isn't covered so you can advocate effectively for the support you need.</p>

                                <h3>What Does NDIS Community Nursing Cover?</h3>
                                <p><strong>Clinical procedures at home</strong> including wound assessment and dressing changes for pressure sores, diabetic ulcers, or chronic wounds, catheter management and changes, stoma care, continence assessment and bladder/bowel programs, PEG feeding tube management, tracheostomy care and suctioning, subcutaneous injections, and blood sugar monitoring and insulin administration for complex diabetes.</p>
                                <p><strong>Health monitoring and management</strong> covers regular vital signs monitoring, medication management and administration, seizure management and emergency response protocols, respiratory support and oxygen therapy management, and coordination with GPs and specialists about your disability-related health.</p>
                                <p><strong>Training and capacity building</strong> includes training support workers or family in specialized care tasks, developing care plans and health protocols, and teaching self-management skills where possible.</p>
                                <p>At Bells NSS, we provide all these services across Melbourne including St Kilda, Northcote, Craigieburn, and Narre Warren. As a registered provider, we know what NDIS will fund and how to document it properly.</p>

                                <h3>What Does NDIS Community Nursing NOT Cover?</h3>
                                <ul>
                                    <li><strong>Short-term post-surgical care:</strong> Hospital responsibility for the first few weeks after surgery.</li>
                                    <li><strong>Emergency medical care:</strong> Ambulance services, emergency departments, or acute illness treatment is never NDIS.</li>
                                    <li><strong>GP or specialist consultations:</strong> Covered by Medicare, not NDIS.</li>
                                    <li><strong>Diagnostic tests and scans:</strong> Blood tests, X-rays, or MRIs come through the health system.</li>
                                    <li><strong>Medications themselves:</strong> Covered by PBS, though NDIS can fund administration of those medications.</li>
                                    <li><strong>Nursing for non-disability health issues:</strong> Standard illness or injury without disability connection does not qualify.</li>
                                </ul>

