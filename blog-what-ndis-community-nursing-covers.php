                                <div class="faq-section mt-5">
                                    <h3>Frequently Asked Questions</h3>
                                    <div class="faq-item">
                                        <p><strong>If I have both NDIS and health care, who pays for what?</strong> Health care covers acute needs and standard medical care. NDIS covers ongoing disability-related supports. Sometimes both systems share costs through formal agreements.</p>
                                    </div>
                                    <div class="faq-item">
                                        <p><strong>Can NDIS pay for nursing in hospital?</strong> No. Hospital care is health system responsibility. NDIS can fund nursing once you're discharged home.</p>
                                    </div>
                                    <div class="faq-item">
                                        <p><strong>What if my nursing needs change suddenly?</strong> Contact your provider immediately. For urgent needs, they should respond quickly. For ongoing changes, you may need a plan review.</p>
                                    </div>
                                    <div class="faq-item">
                                        <p><strong>How many nursing visits can I have per week?</strong> It depends on your assessed needs and plan budget. Some people need daily visits, others weekly or monthly. There's no standard number.</p>
                                    </div>
                                    <div class="faq-item">
                                        <p><strong>Can I choose which nurse visits me?</strong> You can request specific nurses for cultural or gender preferences. Good providers like us try to maintain consistency with familiar faces.</p>
