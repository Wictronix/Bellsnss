                                <p class="lead">Being stuck at home because you can't get anywhere is soul-crushing. You want to see friends, attend your community group, go to family gatherings, or just grab coffee somewhere other than your kitchen. But when getting there feels impossible, those connections start fading.</p>
                                <p>NDIS travel assistance for social activities can fix this. It's not about luxury outings. It's about staying connected to the people and places that make life worth living.</p>

                                <h3>What Travel Support Can NDIS Fund?</h3>
                                <p>NDIS travel assistance for social activities helps you get to community participation activities when regular transport doesn't work for you. This can include:</p>
                                <ul>
                                    <li>A support worker accompanying you on public transport if you need supervision or help navigating</li>
                                    <li>Transport provided directly by your support worker in their vehicle</li>
                                    <li>Funding for accessible taxis or rideshare for approved activities</li>
                                    <li>Assistance to learn how to use public transport independently over time</li>
                                </ul>
                                <p>The catch? The travel has to be for NDIS-related activities, not just anywhere you want to go. Medical appointments, social groups, community events, cultural celebrations, recreational activities, and visiting family all typically qualify.</p>
                                <p>At Bells NSS, we provide NDIS travel assistance for social activities across Melbourne including Camberwell, Mentone, Epping, and Werribee. Our multicultural team understands that your community might be across town, not around the corner.</p>

                                <h3>How Do I Access NDIS Travel Assistance?</h3>
                                <p>Travel assistance needs to be in your NDIS plan under Core Supports (Transport). To get it funded: explain during planning that you can't use public transport independently due to your disability, show that mainstream transport options don't meet your access needs, and demonstrate that travel support will help you achieve your social participation goals.</p>
                                <p>Once it's in your plan, you choose how to use those transport funds. Some people use them for support worker accompaniment, others for taxi vouchers, others for a bit of both. The funding isn't unlimited, so you need to be strategic about which activities matter most to you.</p>

