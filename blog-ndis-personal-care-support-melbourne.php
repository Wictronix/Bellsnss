                                <p class="lead">Starting each day with confidence matters. For many NDIS participants in
                                    Melbourne, personal care support is the foundation that makes independent, dignified
                                    daily living possible. Whether you need assistance with showering, dressing,
                                    grooming, or safe transfers, NDIS personal care is designed to give you exactly the
                                    help you need , on your terms. This guide explains what's included, how it's funded,
                                    and what to expect from a quality provider.</p>

                                <h3>What Is NDIS Personal Care?</h3>
                                <p>Personal care under the NDIS refers to assistance with the activities of daily living
                                    that a participant finds difficult due to their disability. It is provided by
                                    trained support workers , not nurses , and is funded under Core Supports, Budget
                                    Category 01: Assistance with Daily Life. Personal care is one of the most widely
                                    used supports across all NDIS participant types, from younger adults with physical
                                    disabilities to older participants managing neurological conditions.</p>

                                <h3>What Does NDIS Personal Care Include?</h3>
                                <p>NDIS personal care covers a broad range of daily tasks, including:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li>Showering, bathing, and hygiene support</li>
                                    <li>Toileting and continence assistance</li>
                                    <li>Dressing and undressing</li>
                                    <li>Hair care, oral hygiene, skincare, and grooming</li>
                                    <li>Safe mobility support , transfers using hoists, slide sheets, and manual
                                        handling techniques</li>
                                    <li>Meal assistance for participants with swallowing difficulties or limited hand
                                        function</li>
                                    <li>Medication prompts and reminders (not administration , that requires a nurse)
                                    </li>
                                    <li>Pressure care support , repositioning to prevent skin breakdown</li>
                                </ul>
                                <p>The goal is always to preserve your independence and dignity, doing with you rather
                                    than for you wherever possible.</p>

                                <h3>What Is NOT Covered Under Personal Care?</h3>
                                <p>Personal care does not cover clinical or medical interventions , those fall under
                                    community nursing. It also does not cover household tasks like cleaning, cooking, or
                                    gardening , those are funded separately under Household Tasks supports.
                                    Understanding these distinctions helps ensure your NDIS budget is used in the right
                                    categories.</p>

                                <h3>How Is Personal Care Funded in Your NDIS Plan?</h3>
                                <p>Personal care is funded from your Core Supports , Assistance with Daily Life budget.
                                    For the 2025-26 financial year, the NDIS Price Guide sets the standard weekday
                                    hourly rate for personal care at $70.23 per hour, with higher rates applying on
                                    evenings, weekends, and public holidays. If personal care is currently not in your
                                    plan, you can request it at your next plan review by providing supporting evidence
                                    from your GP, occupational therapist, or treating specialist confirming the
                                    functional impact of your disability on daily self-care.</p>

                                <h3>What to Expect From a Bell's NSS Support Worker</h3>
                                <p>When you begin personal care with Bell's NSS, we start with a free intake
                                    conversation to understand your routine, preferences, cultural background, and any
                                    specific medical considerations. We then match you with a support worker based on
                                    compatibility , not just availability. Our support workers are trained in safe
                                    manual handling, privacy-first personal care, and culturally sensitive practice.
                                    Many of our staff are multilingual, which matters deeply for personal care , where
                                    clear communication, trust, and comfort are essential to a positive experience.</p>

                                <h3>Your Rights During Personal Care</h3>
                                <p>Under the NDIS Code of Conduct, you have the right to:</p>
                                <ul style="padding-left: 20px; margin-bottom: 20px;">
                                    <li>Choose who provides your personal care and request a different worker if needed
                                    </li>
                                    <li>Have a support person or family member present during care if you prefer</li>
                                    <li>Set clear boundaries about how and when care is delivered</li>
                                    <li>Receive services free from abuse, neglect, or disrespect</li>
                                </ul>
                                <p>If at any point you feel uncomfortable with a support worker, Bell's NSS will arrange
                                    a replacement without question. Your comfort is non-negotiable.</p>

