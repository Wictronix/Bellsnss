                                <p class="lead">Watching your elderly parent struggle with tasks that used to be automatic is hard. When aging combines with disability, simple things like showering or making a meal become major challenges. If your parent is on the NDIS, you're probably wondering: what daily living support for elderly participants is actually available?</p>
                                <p>The answer is more comprehensive than most families realize, but it comes with some complications around aged care versus NDIS. Let's break it down.</p>

                                <h3>Can Elderly People Access NDIS?</h3>
                                <p>Yes, but there's a catch. If your parent became an NDIS participant before turning 65, they can usually continue with NDIS even as they age. If they're trying to access NDIS for the first time after 65, they'll likely be directed to aged care instead.</p>
                                <p>This matters because aged care and NDIS work differently. NDIS is generally more flexible and can fund higher support levels, which is why families often prefer to stay with NDIS if possible. Daily living support for elderly NDIS participants can be substantial, covering everything from personal care to complex nursing, as long as the needs relate to their disability, not just normal aging.</p>

                                <h3>What's the Difference Between NDIS and Aged Care?</h3>
                                <ul>
                                    <li><strong>NDIS</strong> is for people with permanent and significant disabilities. It's more individualized, more flexible, can fund higher support levels, and focuses on participant choice and control.</li>
                                    <li><strong>Aged Care</strong> is for people 65 and older who need support due to aging. It has set care packages, less flexibility, lower funding caps, and more standardized approaches.</li>
                                </ul>
                                <p>Some elderly people qualify for both systems for different needs. Your parent might get NDIS for disability-related support and aged care for age-related support. This gets complicated fast, which is why having a provider who understands both systems helps.</p>
                                <p>At Bells NSS, we work with NDIS participants across Melbourne including Balwyn, Brighton, Bentleigh, and Caulfield. We're a registered provider familiar with navigating NDIS for elderly participants, including those with complex age-related conditions alongside their disability.</p>

